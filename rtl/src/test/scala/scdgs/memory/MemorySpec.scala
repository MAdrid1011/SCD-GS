      dut.io.read.tier.expect(ScdGsConsts.TierCandidate.U)
      dut.io.read.row.expect(7.U)
      dut.io.read.hotness.expect(9.U)
      dut.io.read.delta.expect(127.U)
      dut.io.read.energy.expect(fpHalf.U)
      dut.io.read.samples.expect(5.U)
      dut.io.read.touched.expect(true.B)
    }
  }

  test("StateSPM preserves one owned state copy and holds a cold candidate through its fill") {
    simulate(new StateSpm(ScdGsParams(maxGaussians = 16))) { dut =>
      dut.io.seedIn.valid.poke(false.B)
      dut.io.candidateFillIn.valid.poke(false.B)
      dut.io.write.valid.poke(false.B)
      dut.io.read.valid.poke(false.B)
      dut.io.readResp.ready.poke(false.B)
      dut.io.candidateReq.ready.poke(false.B)
      dut.io.optimizerReadGid.poke(0.U)
      dut.clock.step()

      // StateSeed establishes one active copy and explicitly
      // zeroes Adam state before any optimizer update is allowed.
      driveState(dut.io.seedIn.bits.state, gid = 7)
      dut.io.seedIn.bits.tier.poke(ScdGsConsts.TierActive.U)
      dut.io.seedIn.valid.poke(true.B)
      stepUntil(dut.clock, 4)(dut.io.seedIn.ready.peek().litToBoolean)
      dut.clock.step()
      dut.io.seedIn.valid.poke(false.B)

      dut.io.optimizerReadGid.poke(7.U)
      dut.clock.step()
      dut.io.optimizerValid.expect(true.B)
      dut.io.optimizerState.adamMoment(0).expect(fpZero.U)
      dut.io.optimizerState.adamVariance(0).expect(fpZero.U)

      driveStateWrite(dut.io.write.bits, gid = 7)
      dut.io.write.bits.state.mean(0).poke(fpOne.U)
      dut.io.write.bits.adamMoment(0).poke(fpHalf.U)
      dut.io.write.bits.adamVariance(0).poke(fpTenth.U)
      dut.io.write.valid.poke(true.B)
      dut.clock.step()
      dut.io.write.valid.poke(false.B)

      dut.io.optimizerReadGid.poke(7.U)
      dut.clock.step()
      dut.io.optimizerValid.expect(true.B)
      dut.io.optimizerState.state.mean(0).expect(fpOne.U)
      dut.io.optimizerState.adamMoment(0).expect(fpHalf.U)
      dut.io.optimizerState.adamVariance(0).expect(fpTenth.U)

      // A second external seed cannot overwrite a live Gaussian or reset its
      // Adam vectors outside the TUU canonical-update path.
      driveState(dut.io.seedIn.bits.state, gid = 7)
      dut.io.seedIn.bits.state.mean(0).poke(fpHalf.U)
      dut.io.seedIn.bits.tier.poke(ScdGsConsts.TierActive.U)
      dut.io.seedIn.valid.poke(true.B)
      stepUntil(dut.clock, 4)(dut.io.seedIn.ready.peek().litToBoolean)
      dut.clock.step()
      dut.io.seedIn.valid.poke(false.B)
      dut.io.invalidInputCount.expect(1.U)
      dut.io.optimizerReadGid.poke(7.U)
      dut.clock.step()
      dut.io.optimizerState.state.mean(0).expect(fpOne.U)
      dut.io.optimizerState.adamMoment(0).expect(fpHalf.U)
      dut.io.optimizerState.adamVariance(0).expect(fpTenth.U)

      dut.io.read.bits.gid.poke(7.U)
      dut.io.read.bits.frameId.poke(1.U)
      dut.io.read.bits.tier.poke(ScdGsConsts.TierActive.U)
      dut.io.read.bits.row.poke(7.U)
      dut.io.read.valid.poke(true.B)
      dut.clock.step()
      dut.io.read.valid.poke(false.B)
      dut.io.readResp.valid.expect(true.B)
      dut.io.readResp.bits.hit.expect(true.B)
      dut.io.readResp.bits.state.mean(0).expect(fpOne.U)
      dut.io.readResp.ready.poke(true.B)
      dut.clock.step()
      dut.io.readResp.ready.poke(false.B)

      // A candidate StateSeed establishes only an initial payload. A candidate
      // read still requires the explicit refill transaction before CIU can
      // observe a complete StateSPM response.
      driveState(dut.io.seedIn.bits.state, gid = 9)
      dut.io.seedIn.bits.tier.poke(ScdGsConsts.TierCandidate.U)
      dut.io.seedIn.valid.poke(true.B)
      stepUntil(dut.clock, 4)(dut.io.seedIn.ready.peek().litToBoolean)
      dut.clock.step()
      dut.io.seedIn.valid.poke(false.B)
      // Candidate state is GID-indexed. A nonmatching row value must not
      // affect the request address or matching fill.
      dut.io.read.bits.gid.poke(9.U)
      dut.io.read.bits.frameId.poke(2.U)
      dut.io.read.bits.tier.poke(ScdGsConsts.TierCandidate.U)
      dut.io.read.bits.row.poke(2.U)
      dut.io.read.valid.poke(true.B)
      stepUntil(dut.clock, 4)(dut.io.read.ready.peek().litToBoolean)
      dut.clock.step()
      dut.io.read.valid.poke(false.B)
      dut.io.readResp.valid.expect(false.B)
      dut.io.candidateReq.valid.expect(true.B)
      dut.io.candidateReq.bits.bytes.expect(64.U)
      dut.io.candidateReq.bits.address.expect((9 * 64).U)
      dut.io.candidateReq.ready.poke(true.B)
      dut.clock.step()
      dut.io.candidateReq.ready.poke(false.B)
      driveCandidateFill(dut.io.candidateFillIn.bits, gid = 9)
      dut.io.candidateFillIn.bits.state.mean(0).poke(fpHalf.U)
      dut.io.candidateFillIn.valid.poke(true.B)
      stepUntil(dut.clock, 4)(dut.io.candidateFillIn.ready.peek().litToBoolean)
      dut.clock.step()
      dut.io.candidateFillIn.valid.poke(false.B)
      dut.io.readResp.valid.expect(true.B)
      dut.io.readResp.bits.hit.expect(true.B)
      dut.io.readResp.bits.state.mean(0).expect(fpHalf.U)
      dut.io.readResp.ready.poke(true.B)
      dut.clock.step()
      dut.io.readResp.ready.poke(false.B)

      dut.io.read.bits.gid.poke(8.U)
      dut.io.read.bits.frameId.poke(2.U)
      dut.io.read.bits.tier.poke(ScdGsConsts.TierCandidate.U)
      dut.io.read.bits.row.poke(3.U)
      dut.io.read.valid.poke(true.B)
      stepUntil(dut.clock, 4)(dut.io.read.ready.peek().litToBoolean)
      dut.clock.step()
      dut.io.read.valid.poke(false.B)
      dut.io.candidateReq.valid.expect(true.B)
      dut.io.candidateReq.bits.bytes.expect(64.U)
      dut.io.candidateReq.bits.address.expect((8 * 64).U)

      // A cold read is not answered with a placeholder. It remains pending
      // until the matching complete candidate-state fill is supplied.
      dut.io.candidateReq.ready.poke(true.B)
      dut.clock.step()
      driveCandidateFill(dut.io.candidateFillIn.bits, gid = 8)
      dut.io.candidateFillIn.bits.state.mean(0).poke(fpHalf.U)
      dut.io.candidateFillIn.bits.adamMoment(0).poke(fpTenth.U)
      dut.io.candidateFillIn.bits.adamVariance(0).poke(fpHundredth.U)
      dut.io.candidateFillIn.valid.poke(true.B)
      dut.clock.step()
      dut.io.candidateFillIn.valid.poke(false.B)
      dut.io.readResp.valid.expect(true.B)
      dut.io.readResp.bits.hit.expect(true.B)
      dut.io.readResp.bits.frameId.expect(2.U)
      dut.io.readResp.bits.state.mean(0).expect(fpHalf.U)

      // A candidate becomes locally reusable only after its matching complete
      // refill. The next candidate read therefore emits no second request.
      dut.io.readResp.ready.poke(true.B)
      dut.clock.step()
      dut.io.readResp.ready.poke(false.B)
      dut.io.candidateReq.ready.poke(false.B)
      dut.io.optimizerReadGid.poke(8.U)
      dut.clock.step()
      dut.io.optimizerValid.expect(true.B)
      dut.io.optimizerState.adamMoment(0).expect(fpTenth.U)
      dut.io.optimizerState.adamVariance(0).expect(fpHundredth.U)
      dut.io.read.bits.gid.poke(8.U)
      dut.io.read.bits.frameId.poke(3.U)
      dut.io.read.bits.tier.poke(ScdGsConsts.TierCandidate.U)
      dut.io.read.bits.row.poke(1.U)
      dut.io.read.valid.poke(true.B)
      stepUntil(dut.clock, 4)(dut.io.read.ready.peek().litToBoolean)
      dut.clock.step()
      dut.io.read.valid.poke(false.B)
      dut.io.readResp.valid.expect(true.B)
      dut.io.readResp.bits.hit.expect(true.B)
      dut.io.readResp.bits.state.mean(0).expect(fpHalf.U)
      dut.io.candidateReq.valid.expect(false.B)

      // FRU's explicit resident row changes the one StateSPM copy. A following
      // TUU write must update that resident row, not recreate an active copy.
      dut.io.readResp.ready.poke(true.B)
      dut.clock.step()
      dut.io.readResp.ready.poke(false.B)
      dut.io.read.bits.gid.poke(7.U)
      dut.io.read.bits.frameId.poke(4.U)
      dut.io.read.bits.tier.poke(ScdGsConsts.TierResident.U)
      dut.io.read.bits.row.poke(11.U)
      dut.io.read.valid.poke(true.B)
      stepUntil(dut.clock, 4)(dut.io.read.ready.peek().litToBoolean)
      dut.clock.step()
      dut.io.read.valid.poke(false.B)
      dut.io.readResp.valid.expect(true.B)
      dut.io.readResp.bits.hit.expect(true.B)
      dut.io.readResp.bits.state.mean(0).expect(fpOne.U)
      dut.io.readResp.ready.poke(true.B)
      dut.clock.step()
      dut.io.readResp.ready.poke(false.B)

      driveStateWrite(dut.io.write.bits, gid = 7)
      dut.io.write.bits.state.mean(0).poke(fpHalf.U)
      dut.io.write.valid.poke(true.B)
      stepUntil(dut.clock, 4)(dut.io.write.ready.peek().litToBoolean)
      dut.clock.step()
      dut.io.write.valid.poke(false.B)

      dut.io.read.bits.gid.poke(7.U)
      dut.io.read.bits.frameId.poke(5.U)
      dut.io.read.bits.tier.poke(ScdGsConsts.TierResident.U)
      dut.io.read.bits.row.poke(11.U)
      dut.io.read.valid.poke(true.B)
      stepUntil(dut.clock, 4)(dut.io.read.ready.peek().litToBoolean)
      dut.clock.step()
      dut.io.read.valid.poke(false.B)
      dut.io.readResp.valid.expect(true.B)
      dut.io.readResp.bits.state.mean(0).expect(fpHalf.U)

      // Moving back through another explicit FRU row proves the old active
      // copy was invalidated and does not overwrite the resident update.
      dut.io.readResp.ready.poke(true.B)
      dut.clock.step()
      dut.io.readResp.ready.poke(false.B)
      dut.io.read.bits.gid.poke(7.U)
      dut.io.read.bits.frameId.poke(6.U)
      dut.io.read.bits.tier.poke(ScdGsConsts.TierActive.U)
      dut.io.read.bits.row.poke(19.U)
      dut.io.read.valid.poke(true.B)
      stepUntil(dut.clock, 4)(dut.io.read.ready.peek().litToBoolean)
      dut.clock.step()
      dut.io.read.valid.poke(false.B)
      dut.io.readResp.valid.expect(true.B)
      dut.io.readResp.bits.hit.expect(true.B)
      dut.io.readResp.bits.state.mean(0).expect(fpHalf.U)

      // A five-frame FRU allocation may reuse a physical partition row before
      // the displaced Gaussian is selected again. StateSPM marks the
      // GID-indexed candidate payload as requiring a refill before a later
      // placement can expose it to CIU.
      dut.io.readResp.ready.poke(true.B)
      dut.clock.step()
      dut.io.readResp.ready.poke(false.B)

      driveState(dut.io.seedIn.bits.state, gid = 10)
      dut.io.seedIn.bits.tier.poke(ScdGsConsts.TierActive.U)
      dut.io.seedIn.valid.poke(true.B)
      stepUntil(dut.clock, 4)(dut.io.seedIn.ready.peek().litToBoolean)
      dut.clock.step()
      dut.io.seedIn.valid.poke(false.B)
      driveStateWrite(dut.io.write.bits, gid = 10)
      dut.io.write.bits.state.mean(0).poke(fpHalf.U)
      dut.io.write.bits.adamMoment(0).poke(fpTenth.U)
      dut.io.write.bits.adamVariance(0).poke(fpHundredth.U)
      dut.io.write.valid.poke(true.B)
      stepUntil(dut.clock, 4)(dut.io.write.ready.peek().litToBoolean)
      dut.clock.step()
      dut.io.write.valid.poke(false.B)

      driveState(dut.io.seedIn.bits.state, gid = 11)
      dut.io.seedIn.bits.tier.poke(ScdGsConsts.TierResident.U)
      dut.io.seedIn.valid.poke(true.B)
      stepUntil(dut.clock, 4)(dut.io.seedIn.ready.peek().litToBoolean)
      dut.clock.step()
      dut.io.seedIn.valid.poke(false.B)

      // GID 11 moves to active row zero, which is currently owned by GID 10.
      // The move must not destroy GID 10 before it is later requested in the
      // resident partition selected by FRU.
      dut.io.read.bits.gid.poke(11.U)
      dut.io.read.bits.frameId.poke(7.U)
      dut.io.read.bits.tier.poke(ScdGsConsts.TierActive.U)
      dut.io.read.bits.row.poke(0.U)
      dut.io.read.valid.poke(true.B)
      stepUntil(dut.clock, 4)(dut.io.read.ready.peek().litToBoolean)
      dut.clock.step()
      dut.io.read.valid.poke(false.B)
      dut.io.readResp.valid.expect(true.B)
      dut.io.readResp.bits.hit.expect(true.B)
      dut.io.readResp.ready.poke(true.B)
      dut.clock.step()
      dut.io.readResp.ready.poke(false.B)

      dut.io.read.bits.gid.poke(10.U)
      dut.io.read.bits.frameId.poke(8.U)
      dut.io.read.bits.tier.poke(ScdGsConsts.TierResident.U)
      dut.io.read.bits.row.poke(0.U)
      dut.io.read.valid.poke(true.B)
      stepUntil(dut.clock, 4)(dut.io.read.ready.peek().litToBoolean)
      dut.clock.step()
      dut.io.read.valid.poke(false.B)
      dut.io.readResp.valid.expect(false.B)
      dut.io.candidateReq.valid.expect(true.B)
      dut.io.candidateReq.bits.address.expect((10 * 64).U)
      dut.io.candidateReq.bits.bytes.expect(64.U)
      dut.io.candidateReq.ready.poke(true.B)
      dut.clock.step()
      dut.io.candidateReq.ready.poke(false.B)
      driveCandidateFill(dut.io.candidateFillIn.bits, gid = 10)
      dut.io.candidateFillIn.bits.state.mean(0).poke(fpHalf.U)
      dut.io.candidateFillIn.bits.adamMoment(0).poke(fpTenth.U)
      dut.io.candidateFillIn.bits.adamVariance(0).poke(fpHundredth.U)
      dut.io.candidateFillIn.valid.poke(true.B)
      stepUntil(dut.clock, 4)(dut.io.candidateFillIn.ready.peek().litToBoolean)
      dut.clock.step()
      dut.io.candidateFillIn.valid.poke(false.B)
      dut.io.readResp.valid.expect(true.B)
      dut.io.readResp.bits.hit.expect(true.B)
      dut.io.readResp.bits.state.mean(0).expect(fpHalf.U)
      dut.io.readResp.ready.poke(true.B)
      dut.clock.step()
      dut.io.readResp.ready.poke(false.B)
      dut.io.optimizerReadGid.poke(10.U)
      dut.clock.step()
      dut.io.optimizerValid.expect(true.B)
      dut.io.optimizerState.adamMoment(0).expect(fpTenth.U)
      dut.io.optimizerState.adamVariance(0).expect(fpHundredth.U)

      // Confirmation-only metadata may be promoted by FRU before StateSPM has
      // a payload for the GID. The eventual active lookup remains a cold
      // candidate refill and must not return an empty response.
      dut.io.candidateReq.ready.poke(false.B)
      dut.io.read.bits.gid.poke(12.U)
      dut.io.read.bits.frameId.poke(9.U)
      dut.io.read.bits.tier.poke(ScdGsConsts.TierActive.U)
      dut.io.read.bits.row.poke(1.U)
      dut.io.read.valid.poke(true.B)
      stepUntil(dut.clock, 4)(dut.io.read.ready.peek().litToBoolean)
      dut.clock.step()
      dut.io.read.valid.poke(false.B)
      dut.io.candidateReq.valid.expect(true.B)
      dut.io.candidateReq.bits.address.expect((12 * 64).U)
      dut.io.candidateReq.bits.bytes.expect(64.U)
      dut.io.candidateReq.ready.poke(true.B)
      dut.clock.step()
      dut.io.candidateReq.ready.poke(false.B)

      driveCandidateFill(dut.io.candidateFillIn.bits, gid = 12)
      dut.io.candidateFillIn.bits.state.mean(0).poke(fpOne.U)
      dut.io.candidateFillIn.bits.adamMoment(0).poke(fpHalf.U)
