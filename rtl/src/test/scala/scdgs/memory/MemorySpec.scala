/** Tests full-state storage, one-copy placement, and candidate refills. */
class MemorySpec extends AnyFunSuite with Matchers with ChiselSim {
  test("SplatSPM, FrameSPM, and MetaSPM retain the paper-visible records") {
    val p = ScdGsParams(maxGaussians = 16)

    simulate(new SplatSpm(p)) { dut =>
      dut.io.summaryWrite.valid.poke(false.B)
      dut.io.traceWrite.valid.poke(false.B)
      dut.io.summaryReadGid.poke(0.U)
      dut.io.traceReadGid.poke(0.U)
      dut.clock.step()

      driveProjection(dut.io.summaryWrite.bits, gid = 7, frame = 3)
      dut.io.summaryWrite.valid.poke(true.B)
      dut.clock.step()
      dut.io.summaryWrite.valid.poke(false.B)
      dut.io.summaryReadGid.poke(7.U)
      dut.clock.step()
      dut.io.summaryValid.expect(true.B)
      dut.io.summaryRead.gid.expect(7.U)
      dut.io.summaryRead.frameId.expect(3.U)

      dut.io.traceWrite.bits.gid.poke(7.U)
      dut.io.traceWrite.bits.frameId.poke(3.U)
      dut.io.traceWrite.bits.pixel.poke(19.U)
      dut.io.traceWrite.bits.blendOrder.poke(2.U)
      dut.io.traceWrite.bits.coverage.poke(fpHalf.U)
      dut.io.traceWrite.bits.transmittance.poke(fpTenth.U)
      (0 until 3).foreach { channel => dut.io.traceWrite.bits.color(channel).poke(fpTenth.U) }
      driveProjection(dut.io.traceWrite.bits.projection, gid = 7, frame = 3)
      dut.io.traceWrite.bits.path.poke(ScdGsConsts.PathLight.U)
      dut.io.traceWrite.valid.poke(true.B)
      dut.clock.step()
      dut.io.traceWrite.valid.poke(false.B)
      dut.io.traceReadGid.poke(7.U)
      dut.clock.step()
      dut.io.traceValid.expect(true.B)
      dut.io.traceRead.pixel.expect(19.U)
      dut.io.traceRead.blendOrder.expect(2.U)
    }

    simulate(new FrameSpm(p, entries = 32)) { dut =>
      dut.io.targetWrite.valid.poke(false.B)
      dut.io.renderWrite.valid.poke(false.B)
      dut.io.targetReadPixel.poke(0.U)
      dut.io.renderReadPixel.poke(0.U)
      dut.clock.step()

      dut.io.targetWrite.bits.pixel.poke(19.U)
      dut.io.targetWrite.bits.frameId.poke(3.U)
      (0 until 3).foreach { channel => dut.io.targetWrite.bits.rgb(channel).poke(fpHalf.U) }
      dut.io.targetWrite.valid.poke(true.B)
      dut.clock.step()
      dut.io.targetWrite.valid.poke(false.B)
      dut.io.targetReadPixel.poke(19.U)
      dut.clock.step()
      dut.io.targetValid.expect(true.B)
      dut.io.targetRead.frameId.expect(3.U)
      dut.io.targetReadPixel.poke(51.U)
      dut.clock.step()
      dut.io.targetValid.expect(false.B)

      dut.io.renderWrite.bits.pixel.poke(19.U)
      dut.io.renderWrite.bits.frameId.poke(3.U)
      (0 until 3).foreach { channel => dut.io.renderWrite.bits.rgb(channel).poke(fpTenth.U) }
      dut.io.renderWrite.bits.transmittance.poke(fpTenth.U)
      dut.io.renderWrite.valid.poke(true.B)
      dut.clock.step()
      dut.io.renderWrite.valid.poke(false.B)
      dut.io.renderReadPixel.poke(19.U)
      dut.clock.step()
      dut.io.renderValid.expect(true.B)
      dut.io.renderRead.transmittance.expect(fpTenth.U)
      dut.io.renderReadPixel.poke(51.U)
      dut.clock.step()
      dut.io.renderValid.expect(false.B)
    }

    simulate(new MetaSpm(p)) { dut =>
      dut.io.write.valid.poke(false.B)
      dut.io.writeGid.poke(0.U)
      dut.io.readGid.poke(0.U)
      dut.clock.step()
      dut.io.readValid.expect(false.B)

      dut.io.writeGid.poke(7.U)
      dut.io.write.bits.tier.poke(ScdGsConsts.TierCandidate.U)
      dut.io.write.bits.row.poke(7.U)
      dut.io.write.bits.hotness.poke(9.U)
      dut.io.write.bits.delta.poke(127.U)
      dut.io.write.bits.energy.poke(fpHalf.U)
